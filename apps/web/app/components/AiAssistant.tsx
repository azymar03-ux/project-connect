"use client";
import { useMyProjects } from "../../lib/useMyProjects";
import ConversationAssistant from "./ConversationAssistant";
import { useEffect, useState } from "react";
import {
  Sparkles,
  Loader2,
  ShieldAlert,
  ListChecks,
  BookOpen,
  ArrowUpRight,
  Bot,
  History,
} from "lucide-react";
async function api(path: string, method = "GET", data?: unknown) {
  const r = await fetch("/api/" + path, {
    method,
    headers: { "Content-Type": "application/json" },
    ...(data ? { body: JSON.stringify(data) } : {}),
  });
  const b = await r.json();
  if (!r.ok) throw new Error(b.message || "Request failed.");
  return b;
}
const examples = [
  "I want to build an autonomous obstacle-avoiding drone using OpenCV & Arduino.",
  "A realtime collaborative SaaS workspace using Next.js 15, Supabase, and Tailwind.",
  "An IoT smart energy monitor with ESP32, MQTT, and a live web dashboard.",
  "An AI model that detects crop disease from leaf photos using PyTorch and FastAPI.",
];
export default function AiAssistant({
  user,
  projects,
  onSignIn,
  notify,
}: {
  user: any;
  projects: any[];
  onSignIn: () => void;
  notify: (s: string) => void;
}) {
  const [prompt, setPrompt] = useState(""),
    [plan, setPlan] = useState<any>(null),
    [busy, setBusy] = useState(false),
    [status, setStatus] = useState<any>(null),
    [history, setHistory] = useState<any[]>([]),
    [target, setTarget] = useState(""),
    [consent, setConsent] = useState(false);
  const owned = useMyProjects(user?.id);
  const mine = owned.projects;
  useEffect(() => {
    api("ai/status")
      .then(setStatus)
      .catch(() => {});
    if (user)
      api("ai/plans")
        .then(setHistory)
        .catch(() => {});
  }, [user?.id]);
  useEffect(() => {
    if (!target && mine[0]) setTarget(mine[0].id);
  }, [mine.length]);
  async function generate(e: React.FormEvent) {
    e.preventDefault();
    if (!user) return onSignIn();
    setBusy(true);
    try {
      const p = await api("ai/plan", "POST", {
        prompt,
        providerConsent: consent,
      });
      setPlan(p);
      setHistory((h) => [p, ...h].slice(0, 20));
    } catch (e: any) {
      notify(e.message);
    } finally {
      setBusy(false);
    }
  }
  const data = plan?.plan;
  return (
    <>
      <div className="page-heading">
        <div>
          <div className="eyebrow">YOUR IDEA. A SMARTER STARTING POINT.</div>
          <h1>AI project planner</h1>
          <p>
            Describe what you want to build and get a staged roadmap, suggested
            technologies, safety notes and matching resources.
          </p>
        </div>
      </div>
      {owned.error && (
        <p className="form-error" role="alert">
          {owned.error}
        </p>
      )}
      <ConversationAssistant user={user} notify={notify} projects={mine} />
      <div className="ai-layout">
        <section className="panel">
          <form onSubmit={generate}>
            <label className="field">
              What do you want to build?
              <textarea
                value={prompt}
                onChange={(e) => setPrompt(e.target.value)}
                minLength={10}
                maxLength={1500}
                required
                rows={4}
                placeholder="Describe your project idea…"
              />
            </label>
            <div className="tags ai-examples">
              {examples.map((x) => (
                <button type="button" key={x} onClick={() => setPrompt(x)}>
                  {x}
                </button>
              ))}
            </div>
            {status?.llmConfigured && (
              <label className="checkbox-field">
                <input
                  type="checkbox"
                  checked={consent}
                  onChange={(e) => setConsent(e.target.checked)}
                />
                I consent to sending this project description to the live AI
                provider.
              </label>
            )}
            <button
              className="primary-button full-width"
              disabled={busy || Boolean(status?.llmConfigured && !consent)}
            >
              {busy ? (
                <Loader2 className="spin" size={16} />
              ) : (
                <Sparkles size={16} />
              )}
              Generate roadmap
            </button>
          </form>
          <p className="integration-note">
            {status?.llmConfigured
              ? "Plans are generated by the configured language model and validated before display."
              : "No AI provider key is configured, so plans come from curated built-in templates. Add OPENAI_API_KEY to enable model-generated plans."}{" "}
            Always review plans; this is not certified engineering advice.
          </p>
          {history.length > 0 && (
            <>
              <h3>
                <History size={14} /> Recent plans
              </h3>
              {history.slice(0, 6).map((h) => (
                <button
                  key={h.id}
                  className="workspace-resource-choice"
                  onClick={() => setPlan(h)}
                >
                  {h.prompt.slice(0, 60)}
                  {h.prompt.length > 60 ? "…" : ""}
                  <small>{h.source === "llm" ? "AI" : "Template"}</small>
                </button>
              ))}
            </>
          )}
        </section>
        <section className="panel ai-result">
          {!data ? (
            <div className="empty-state">
              <Bot size={36} />
              <h3>Your roadmap will appear here.</h3>
              <p>Try one of the examples to see how it works.</p>
            </div>
          ) : (
            <>
              <div className="eyebrow">
                {plan.source === "llm"
                  ? "MODEL-GENERATED PLAN"
                  : "TEMPLATE PLAN"}
              </div>
              <h2>{data.summary}</h2>
              <button
                className="secondary-button"
                disabled={busy}
                onClick={async () => {
                  if (
                    !window.confirm(
                      "Delete this saved roadmap? Imported workspace tasks will not be deleted.",
                    )
                  )
                    return;
                  setBusy(true);
                  try {
                    await api("ai/plans/" + plan.id, "DELETE");
                    setHistory((h) => h.filter((p) => p.id !== plan.id));
                    setPlan(null);
                    notify(
                      "Roadmap content deleted; the daily usage counter is retained.",
                    );
                  } catch (e: any) {
                    notify(e.message);
                  } finally {
                    setBusy(false);
                  }
                }}
              >
                Delete saved roadmap
              </button>
              <h3>
                <ListChecks size={15} /> Roadmap
              </h3>
              <ol className="roadmap">
                {data.steps.map((s: any, i: number) => (
                  <li key={i}>
                    <strong>{s.title}</strong>
                    <p>{s.detail}</p>
                  </li>
                ))}
              </ol>
              <h3>Recommended technologies</h3>
              <div className="tags">
                {data.technologies.map((t: string) => (
                  <span key={t}>{t}</span>
                ))}
              </div>
              {data.safety.length > 0 && (
                <div className="safety-box">
                  <ShieldAlert size={16} />
                  <div>
                    <strong>Safety notes</strong>
                    <ul>
                      {data.safety.map((s: string) => (
                        <li key={s}>{s}</li>
                      ))}
                    </ul>
                  </div>
                </div>
              )}
              {data.resources?.length > 0 && (
                <>
                  <h3>
                    <BookOpen size={15} /> From the Resource Hub
                  </h3>
                  {data.resources.map((r: any) => (
                    <a
                      key={r.id}
                      className="workspace-resource-choice"
                      href={r.url}
                      target="_blank"
                      rel="noopener noreferrer"
                    >
                      {r.title}
                      <ArrowUpRight size={14} />
                    </a>
                  ))}
                </>
              )}
              <h3>Turn this into tasks</h3>
              {mine.length === 0 ? (
                <p className="muted">
                  Join or create a project to import this roadmap as tasks.
                </p>
              ) : (
                <div className="milestone-form">
                  <select
                    aria-label="Target project"
                    className="status-select"
                    value={target}
                    onChange={(e) => setTarget(e.target.value)}
                  >
                    {mine.map((p) => (
                      <option key={p.id} value={p.id}>
                        {p.title}
                      </option>
                    ))}
                  </select>
                  <button
                    className="primary-button"
                    onClick={async () => {
                      try {
                        const r = await api(
                          `ai/plans/${plan.id}/tasks`,
                          "POST",
                          { projectId: target },
                        );
                        notify(
                          `${r.created} tasks added${r.skipped ? `, ${r.skipped} already existed` : ""}`,
                        );
                      } catch (e: any) {
                        notify(e.message);
                      }
                    }}
                  >
                    <ListChecks size={15} />
                    Add to workspace
                  </button>
                </div>
              )}
            </>
          )}
        </section>
      </div>
    </>
  );
}
